export interface AccountGroupRef {
  id: string;
  name: string;
  mainClass: AccountMainClass;
  incomeStatementSubItem: IncomeStatementSubItem | null;
  balanceSheetItem: BalanceSheetItem | null;
}

export interface AccountGroup {
  id: string;
  name: string;
  mainClass: AccountMainClass;
  incomeStatementSubItem: IncomeStatementSubItem | null;
  balanceSheetItem: BalanceSheetItem | null;
  // Included by the list endpoint, omitted when the relation wasn't loaded.
  accounts?: Account[];
  createdAt: string;
  updatedAt: string;
}

// The accounts the backend posts a journal entry line's VAT to: the VAT of a
// debit line to the receivable account, of a credit line to the payable one.
// Null until the company has picked one.
export interface VatAccounts {
  vatReceivableAccountId: string | null;
  vatPayableAccountId: string | null;
}

export interface Account {
  id: string;
  // Account number is a per-company string (e.g. '1900'), not a numeric id.
  number: string;
  name: string;
  accountGroupId: string | null;
  // Omitted by the serializer when the group relation wasn't loaded.
  accountGroup?: AccountGroupRef | null;
  createdAt: string;
  updatedAt: string;
}
